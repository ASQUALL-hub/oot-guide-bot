"""Generate ootmap/ACTIONS.md from player_moves.py + data/meta/player_actions.json (no ROM needed).
Run by make_metadata.py; animation frame counts are only in the ROM-built ootmap/actions.json."""
import json
import os
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)
import movement_sim as S  # noqa: E402
import player_moves as M  # noqa: E402


def src_ref(src):
    items = src if isinstance(src, list) else [src]
    return ", ".join(f"`{os.path.basename(f)}`" for f, _ in items[:1])


def main():
    with open(os.path.join(ROOT, "data", "meta", "player_actions.json"), encoding="utf-8") as f:
        actions = json.load(f)
    L = []
    w = L.append
    w("# Link's actions and movement")
    w("")
    w("Every action Link can be in, and the physics of every way he moves, read from the decompiled game code.")
    w("This file is generated by `tools/write_actions_doc.py`. Bots should read `actions.json` (built by")
    w("`tools/build.py`): it has the same data plus animation lengths from your ROM and per-frame jump paths.")
    w("")
    w("## Units")
    w("")
    w("- **Speed** is the game's `speedXZ` value. Link actually moves **speed x 1.5 units per game frame**, and NTSC runs")
    w("  **20 game frames per second**. So speed 6.0 is 9 units/frame, or 180 units/second.")
    w("- **Each frame**, vertical speed gains gravity (never below -20), then Link moves by speed x 1.5.")
    w("- **Heights and distances** are in world units, the same as the collision and actor positions in `ootmap/`.")
    w("")
    w("## Ground movement (top speed at full stick, adult, Kokiri boots)")
    w("")
    w("| Move | Inputs | Flat | 10° uphill | 20° | 30° | 40° | Units/frame (flat) | Notes |")
    w("|---|---|---|---|---|---|---|---|---|")
    for g in M.GROUND_MOVES:
        sp = [S.ground_target_speed(g["mode"], g["multiplier"], 6.0, s) for s in (0, 10, 20, 30, 40)]
        w(f"| {g['name']} | {g['inputs']} | " + " | ".join(f"{x:g}" for x in sp) + f" | {S.per_frame(sp[0]):g} | {g['note']} |")
    w("")
    w("Speed limits by boots: " + "; ".join(f"{b['boots']} {b['run_speed_limit']:g}" for b in M.BOOTS) + ".")
    w(f"Speed formula: {M.SPEED_FORMULA['text']}")
    w("")
    w("## Jumps")
    w("")
    w("| Jump | Inputs | Speed | Upward speed | Air frames | Peak height | Distance (flat) | Locked on to an enemy: frames / peak / distance | Momentum |")
    w("|---|---|---|---|---|---|---|---|---|")
    for j in M.JUMPS:
        if j["velocity_y"] is None:
            w(f"| {j['name']} | {j['inputs']} | {j['speed_xz']:g} | {j['conditions']} | – | – | – | – | {j['momentum']} |")
            continue
        a = S.simulate_jump(j["speed_xz"], j["velocity_y"], -1.0)
        b = S.simulate_jump(j["speed_xz"], j["velocity_y"], -1.2)
        w(f"| {j['name']} | {j['inputs']} | {j['speed_xz']:g} | {j['velocity_y']:g} | {a['airtime_frames']} | {a['peak_height']:g} | "
          f"{a['distance']:g} | {b['airtime_frames']} / {b['peak_height']:g} / {b['distance']:g} | {j['momentum']} |")
    w("")
    w("Jump conditions: " + " ".join(f"**{j['name']}:** {j['conditions']}." for j in M.JUMPS if j["velocity_y"] is not None))
    w("")
    w("## Uphill: which move is fastest")
    w("")
    w("Speed is units per frame going straight uphill (adult, Kokiri boots). The sidehop chain counts each hop's airtime")
    w("plus the one landing frame before the next hop can start (Z held).")
    w("")
    w("| Slope | Run | Backwalk | Sidehop chain (average) | Sidehop frames in air |")
    w("|---|---|---|---|---|")
    for s in (0, 10, 20, 30, 40):
        r = S.per_frame(S.ground_target_speed("curved", 1.0, 6.0, s))
        bw = S.per_frame(S.ground_target_speed("linear", 1.5, 6.0, s))
        hop = S.simulate_jump(8.5, 3.5, -1.0, s)
        ch = S.jump_chain(8.5, 3.5, -1.0, s)
        w(f"| {s}° | {r:g} | {bw:g} | {ch['units_per_frame']:g} | {hop['airtime_frames']} |")
    w("")
    w("Backwalking keeps its 1.5x lead over running on every slope. Sidehops aren't slowed by the slope in the air, and")
    w("the next hop starts one frame after landing, so a sidehop chain stays near 12 units/frame uphill and passes")
    w("backwalking on steeper slopes. Very steep floors make Link slide, so check the slope before relying on it.")
    w("")
    w("## Rules the movement follows")
    w("")
    for r in M.RULES:
        w(f"- **{r['rule']}:** {r['effect']} ({src_ref(r['src'])}).")
    w("")
    w("## Speedrun tech")
    w("")
    w("| Technique | Inputs | What it does | Best for | Verified |")
    w("|---|---|---|---|---|")
    for t in M.TECH:
        w(f"| {t['name']} | {t['inputs']} | {t['what']} | {t['best_for']} | {t['verified']} |")
    w("")
    w("### Glitches (community knowledge, not checked against the code)")
    w("")
    w("These are named in the randomizer's logic (`logic/helpers.json`, `--glitches` in `logic_eval.py`).")
    w("")
    for g in M.COMMUNITY_GLITCHES:
        w(f"- **{g['name']}** (`{g['logic_name']}`): {g['what']}.")
    w("")
    w(f"## Every player action ({len(actions)})")
    w("")
    w("Link is always in exactly one of these action states (`Player_Action_*` in `z_player.c`). Many are still unnamed")
    w("in the decomp, so each label here was identified from the animations, sounds and state flags the function uses.")
    w("The evidence is in `actions.json`, and each label's confidence is listed.")
    w("")
    w("| Function | What it is | Category | Confidence | Line |")
    w("|---|---|---|---|---|")
    for a in actions:
        w(f"| `{a['function']}` | {a['label']} | {a['category']} | {a['label_confidence']} | {a['line']} |")
    w("")
    with open(os.path.join(ROOT, "ootmap", "ACTIONS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("wrote ootmap/ACTIONS.md")


if __name__ == "__main__":
    main()
